@app.post("/api/auth/resend-otp")
def resend_otp():

    data = request.get_json(silent=True) or {}

    email = str(
        data.get("email", "")
    ).strip().lower()

    if not EMAIL_REGEX.fullmatch(email):

        return jsonify({
            "error": "Please provide a valid email."
        }), 400

    connection = get_db()

    try:

        user = connection.execute("""
            SELECT
                id,
                name,
                email,
                email_verified
            FROM users
            WHERE email = ?
        """, (email,)).fetchone()

        if not user:

            return jsonify({
                "error": "Account not found. Please register first."
            }), 404

        if user["email_verified"]:

            return jsonify({
                "message": "This email is already verified. You can log in."
            }), 200

        verification = connection.execute("""
            SELECT last_sent_at
            FROM email_verifications
            WHERE user_id = ?
        """, (user["id"],)).fetchone()

        if verification:

            now = datetime.now(timezone.utc)

            elapsed = (
                now - verification["last_sent_at"]
            ).total_seconds()

            remaining = OTP_RESEND_SECONDS - elapsed

            if remaining > 0:

                return jsonify({
                    "error": f"Please wait {int(remaining) + 1} seconds before requesting another OTP."
                }), 429

        otp = create_email_otp(
            connection,
            user["id"]
        )

        connection.commit()

        try:

            send_verification_otp(
                user,
                otp
            )

        except Exception:

            app.logger.exception(
                "Resend OTP email failed."
            )

            return jsonify({
                "error": "Unable to send OTP right now. Please try again later."
            }), 500

        return jsonify({
            "message": "A new verification OTP has been sent to your email."
        }), 200

    except Exception:

        connection.rollback()

        app.logger.exception(
            "Resend OTP failed."
        )

        return jsonify({
            "error": "Unable to resend OTP. Please try again."
        }), 500

    finally:

        connection.close()


