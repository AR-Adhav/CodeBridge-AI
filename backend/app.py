class DatabaseConnection:

    def __init__(self):

        self.connection = psycopg.connect(
            DATABASE_URL,
            row_factory=dict_row,
            connect_timeout=15
        )

    def execute(self, query, parameters=()):

        query = query.replace("?", "%s")

        return self.connection.execute(
            query,
            parameters
        )

    def commit(self):
        self.connection.commit()

    def rollback(self):
        self.connection.rollback()

    def close(self):
        self.connection.close()


def get_db():
    return DatabaseConnection()


def init_db():

    connection = get_db()

    try:

        # USERS TABLE

        connection.execute("""
            CREATE TABLE IF NOT EXISTS users (

                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                name TEXT NOT NULL,

                email TEXT NOT NULL UNIQUE,

                password_hash TEXT NOT NULL,

                role TEXT NOT NULL CHECK (
                    role IN ('job_seeker', 'recruiter', 'admin')
                ),

                recruiter_status TEXT DEFAULT 'not_applicable',

                email_verified BOOLEAN NOT NULL DEFAULT TRUE,

                created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
            )
        """)

        # Add the column safely to existing Neon databases.
        # Existing accounts remain verified.

        connection.execute("""
            ALTER TABLE users
            ADD COLUMN IF NOT EXISTS email_verified
            BOOLEAN NOT NULL DEFAULT TRUE
        """)

        # EMAIL OTP TABLE

        connection.execute("""
            CREATE TABLE IF NOT EXISTS email_verifications (

                user_id BIGINT PRIMARY KEY,

                otp_hash TEXT NOT NULL,

                expires_at TIMESTAMPTZ NOT NULL,

                attempts INTEGER NOT NULL DEFAULT 0,

                last_sent_at TIMESTAMPTZ NOT NULL,

                created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,

                FOREIGN KEY (user_id)
                    REFERENCES users(id)
                    ON DELETE CASCADE
            )
        """)

        # JOBS TABLE

        connection.execute("""
            CREATE TABLE IF NOT EXISTS jobs (

                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                recruiter_id BIGINT,

                title TEXT NOT NULL,

                company TEXT NOT NULL,

                type TEXT NOT NULL,

                level TEXT NOT NULL,

                location TEXT,

                salary TEXT,

                description TEXT,

                skills TEXT,

                status TEXT DEFAULT 'pending',

                created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

                FOREIGN KEY (recruiter_id)
                    REFERENCES users(id)
                    ON DELETE CASCADE
            )
        """)

        # ROADMAP TASKS TABLE

        connection.execute("""
            CREATE TABLE IF NOT EXISTS roadmap_tasks (

                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                user_id BIGINT NOT NULL,

                task_id TEXT NOT NULL,

                task_text TEXT NOT NULL,

                week_number INTEGER NOT NULL,

                completed INTEGER NOT NULL DEFAULT 0,

                completed_at TEXT,

                created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

                UNIQUE(user_id, task_id),

                FOREIGN KEY (user_id)
                    REFERENCES users(id)
                    ON DELETE CASCADE
            )
        """)

        # PROFILE VISITS TABLE

        connection.execute("""
            CREATE TABLE IF NOT EXISTS profile_visits (

                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                user_id BIGINT NOT NULL,

                visit_date TEXT NOT NULL,

                UNIQUE(user_id, visit_date),

                FOREIGN KEY (user_id)
                    REFERENCES users(id)
                    ON DELETE CASCADE
            )
        """)

        connection.commit()

        app.logger.info(
            "Neon PostgreSQL database initialized successfully."
        )

    except Exception:

        connection.rollback()

        app.logger.exception(
            "Database initialization failed."
        )

        raise

    finally:

        connection.close()


