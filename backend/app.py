@app.get("/api/profile/activity")
@login_required
def get_profile_activity():

    user_id = session["user_id"]

    today = date.today()

    start_date = today - timedelta(days=6)

    connection = get_db()

    try:

        visit_rows = connection.execute("""
            SELECT visit_date
            FROM profile_visits
            WHERE user_id = ?
              AND visit_date BETWEEN ? AND ?
        """, (
            user_id,
            start_date.isoformat(),
            today.isoformat()
        )).fetchall()

        visit_dates = {
            row["visit_date"]
            for row in visit_rows
        }

        task_rows = connection.execute("""
            SELECT
                CAST(completed_at AS DATE) AS completion_date,
                COUNT(*) AS task_count
            FROM roadmap_tasks
            WHERE user_id = ?
              AND completed = 1
              AND completed_at IS NOT NULL
              AND CAST(completed_at AS DATE) BETWEEN ? AND ?
            GROUP BY CAST(completed_at AS DATE)
        """, (
            user_id,
            start_date.isoformat(),
            today.isoformat()
        )).fetchall()

        tasks_by_date = {}

        for row in task_rows:

            completion_date = row["completion_date"]

            if hasattr(completion_date, "isoformat"):
                completion_date = completion_date.isoformat()

            tasks_by_date[completion_date] = row["task_count"]

        activity = []

        for offset in range(7):

            curr = start_date + timedelta(days=offset)

            date_string = curr.isoformat()

            activity.append({

                "date": date_string,

                "day": curr.strftime("%a"),

                "visits": (
                    1 if date_string in visit_dates else 0
                ),

                "tasks": int(
                    tasks_by_date.get(date_string, 0)
                )

            })

        active_days = sum(
            1
            for item in activity
            if item["visits"] > 0 or item["tasks"] > 0
        )

        total_tasks = sum(
            item["tasks"]
            for item in activity
        )

        return jsonify({

            "total_tasks_completed": total_tasks,

            "active_days": active_days,

            "consistency": round(
                (active_days / 7) * 100
            ),

            "activity": activity

        }), 200

    finally:

        connection.close()


