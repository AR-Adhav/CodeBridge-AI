@app.post("/api/auth/register")
def register():

    data = request.get_json(silent=True) or {}

    name = str(data.get("name", "")).strip()

    email = str(
        data.get("email", "")
    ).strip().lower()

    password = str(data.get("password", ""))

    role = str(
        data.get("role", "job_seeker")
    ).strip().lower()

    if role not in ("job_seeker", "recruiter"):

        return jsonify({
            "error": "Invalid role."
        }), 400

    if not name or len(name) > 100:

        return jsonify({
            "error": "Please enter a valid name."
        }), 400

    if len(email) > 254 or not EMAIL_REGEX.fullmatch(email):

        return jsonify({
            "error": "Please enter a valid email address."
        }), 400

    if len(password) < 8:

        return jsonify({
            "error": "Password must contain at least 8 characters."
        }), 400

    connection = get_db()

    try:

        existing = connection.execute(
            "SELECT id FROM users WHERE email = ?",
            (email,)
        ).fetchone()

        if existing:

            return jsonify({
                "error": "Email already registered. If your account is not verified, request a new OTP."
            }), 409

        password_hash = generate_password_hash(password)

        recruiter_status = (
            "pending"
            if role == "recruiter"
            else "not_applicable"
        )

        user = connection.execute("""
            INSERT INTO users (
                name,
                email,
                password_hash,
                role,
                recruiter_status,
                email_verified
            )
            VALUES (?, ?, ?, ?, ?, FALSE)
            RETURNING id, name, email, role, recruiter_status
        """, (
            name,
            email,
            password_hash,
            role,
            recruiter_status
        )).fetchone()

        otp = create_email_otp(
            connection,
            user["id"]
        )

        connection.commit()

        try:

            send_verification_otp(
                user,
                otp
            )

        except Exception:

            app.logger.exception(
                "OTP email could not be sent."
            )

            return jsonify({
                "message": "Your account was created, but the verification email could not be sent. Please use Resend OTP.",
                "email": email,
                "verification_required": True
            }), 201

        return jsonify({
            "message": "Registration successful. A verification OTP has been sent to your email.",
            "email": email,
            "verification_required": True
        }), 201

    except psycopg.errors.UniqueViolation:

        connection.rollback()

        return jsonify({
            "error": "Email already registered."
        }), 409

    except Exception:

        connection.rollback()

        app.logger.exception(
            "Registration failed."
        )

        return jsonify({
            "error": "Registration failed. Please try again."
        }), 500

    finally:

        connection.close()


